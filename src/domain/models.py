"""
Domain models for content pipeline
Pure business entities with no external dependencies
"""

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Optional


class ContentFormat(Enum):
    """Supported content formats"""

    SINGLE_TWEET = "Single Tweet"
    THREAD = "Thread"
    POLL = "Poll"
    IMAGE = "Image"


@dataclass
class ContentPillar:
    """Content pillar with weight"""

    name: str
    weight: int

    def __post_init__(self):
        if self.weight < 0 or self.weight > 100:
            raise ValueError(f"Pillar weight must be 0-100, got {self.weight}")


@dataclass
class Account:
    """Account configuration"""

    account_id: str
    username: str
    niche: str
    voice: str
    content_pillars: list[ContentPillar]
    preferred_formats: list[ContentFormat]

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Account":
        """Create Account from config dict"""
        pillars_dict = data.get("content_pillars", {})
        pillars = [
            ContentPillar(name=name, weight=weight)
            for name, weight in pillars_dict.items()
        ]

        format_names = data.get("preferred_formats", [])
        formats = [ContentFormat(fmt) for fmt in format_names]

        return cls(
            account_id=data["account_id"],
            username=data["username"],
            niche=data["niche"],
            voice=data["voice"],
            content_pillars=pillars,
            preferred_formats=formats,
        )

    def get_pillar_by_name(self, name: str) -> Optional[ContentPillar]:
        """Get pillar by name (case-insensitive)"""
        normalized = name.lower().replace("-", " ").replace("_", " ")
        for pillar in self.content_pillars:
            pillar_normalized = pillar.name.lower().replace("-", " ").replace("_", " ")
            if pillar_normalized == normalized:
                return pillar
        return None

    def get_sorted_pillars(self) -> list[ContentPillar]:
        """Get pillars sorted by weight (descending)"""
        return sorted(self.content_pillars, key=lambda p: p.weight, reverse=True)


@dataclass
class Angle:
    """Content angle generated by strategist"""

    title: str
    hook: str
    key_points: list[str]
    value_score: int
    viral_score: int
    recency_score: int
    suggested_formats: list[ContentFormat]
    pillar: str

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "Angle":
        """Create Angle from strategist output"""
        format_names = data.get("suggested_formats", [])
        formats = [ContentFormat(fmt) for fmt in format_names]

        return cls(
            title=data["title"],
            hook=data["hook"],
            key_points=data.get("key_points", []),
            value_score=data.get("value_score", 0),
            viral_score=data.get("viral_score", 0),
            recency_score=data.get("recency_score", 0),
            suggested_formats=formats,
            pillar=data.get("pillar", ""),
        )

    def to_dict(self) -> dict[str, Any]:
        """Convert to dict for serialization"""
        return {
            "title": self.title,
            "hook": self.hook,
            "key_points": self.key_points,
            "value_score": self.value_score,
            "viral_score": self.viral_score,
            "recency_score": self.recency_score,
            "suggested_formats": [fmt.value for fmt in self.suggested_formats],
            "pillar": self.pillar,
        }

    def total_score(self) -> int:
        """Calculate total score"""
        return self.value_score + self.viral_score + self.recency_score


@dataclass
class Content:
    """Generated content"""

    text: str
    content_format: ContentFormat
    topic: str
    angle: Angle
    timestamp: datetime = field(default_factory=datetime.now)

    @property
    def format(self) -> ContentFormat:
        """Backward-compatible format alias"""
        return self.content_format

    def get_format_marker(self) -> str:
        """Get format marker for content"""
        markers = {
            ContentFormat.SINGLE_TWEET: "**SINGLE TWEET:**",
            ContentFormat.THREAD: "**THREAD:**",
            ContentFormat.POLL: "**POLL:**",
            ContentFormat.IMAGE: "**IMAGE:**",
        }
        return markers.get(
            self.content_format, f"**{self.content_format.value.upper()}:**"
        )

    def get_clean_text(self) -> str:
        """Get text without format marker"""
        marker = self.get_format_marker()
        return self.text.replace(marker, "").strip()


@dataclass
class QCResult:
    """Quality control result"""

    score: int
    issues: list[str]
    fixed_content: Optional[str] = None
    passed: bool = field(init=False)

    def __post_init__(self):
        self.passed = self.score >= 7


@dataclass
class VisualConcept:
    """Visual concept for image posts"""

    concept: str
    style: str
    elements: list[str]
    colors: list[str]

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> "VisualConcept":
        """Create VisualConcept from visual AI output"""
        return cls(
            concept=data.get("concept", ""),
            style=data.get("style", ""),
            elements=data.get("elements", []),
            colors=data.get("colors", []),
        )


@dataclass
class GenerationResult:
    """Complete generation result"""

    account: Account
    content: Content
    qc_result: QCResult
    visual_concept: Optional[VisualConcept] = None
    generation_time: float = 0.0
    all_angles: list[Angle] = field(default_factory=list)
    engagement_strategy: Optional[str] = None
    qc_data: dict[str, Any] = field(default_factory=dict)
    visual_brief: Optional[str] = None

    def is_successful(self) -> bool:
        """Check if generation was successful"""
        return self.qc_result.passed

    def get_final_content(self) -> str:
        """Get final content (fixed if available)"""
        if self.qc_result.fixed_content:
            return self.qc_result.fixed_content
        return self.content.text
